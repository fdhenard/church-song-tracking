-- Initial church song tracking schema.

CREATE TABLE person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    time_added TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--;;

CREATE TABLE sermon_series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    time_added TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
)

--;;

CREATE TABLE holiday (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    time_added TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
)

--;;

CREATE TABLE church_service (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE NOT NULL,
    title VARCHAR NOT NULL,
    link_youtube VARCHAR,
    link_vimeo VARCHAR,
    preacher_id BIGINT NOT NULL REFERENCES person(id),
    song_leader_id BIGINT NOT NULL REFERENCES person(id),
    sermon_series_id BIGINT NULL REFERENCES sermon_series(id),
    sermon_title VARCHAR NOT NULL,
    sermon_title_slide_time_youtube VARCHAR NULL,
    sermon_title_slide_time_vimeo VARCHAR NULL,
    sermon_topic VARCHAR NULL,
    holiday_id BIGINT NULL REFERENCES holiday(id),
    interest_for_next_mens_retreat BOOLEAN NOT NULL DEFAULT FALSE,
    time_added TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--;;

CREATE TABLE song (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    artist VARCHAR NOT NULL,
    time_added TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--;;

CREATE TABLE song_variation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    song_id BIGINT NOT NULL REFERENCES song(id),
    variation_name VARCHAR NOT NULL,
    example_link VARCHAR,
    prominent_electric_guitar BOOLEAN NOT NULL DEFAULT FALSE,
    time_added TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--;;

CREATE TABLE song_performance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    song_variation_id BIGINT NOT NULL REFERENCES song_variation(id),
    church_service_id BIGINT NOT NULL REFERENCES church_service(id),
    order_in_service INTEGER NOT NULL,
    time_in_service_vimeo VARCHAR NULL,
    time_in_service_youtube VARCHAR NULL,
    time_added TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
