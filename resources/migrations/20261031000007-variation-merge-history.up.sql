CREATE TABLE variation_merge_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 song_id BIGINT NOT NULL,
 retained_variation_id BIGINT NOT NULL,
 merged_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 before_data VARCHAR NOT NULL,
 after_data VARCHAR NOT NULL,
 performance_count BIGINT NOT NULL
);
--;;
CREATE TABLE variation_merge_alias (
 old_variation_id BIGINT PRIMARY KEY,
 canonical_variation_id BIGINT NOT NULL REFERENCES song_variation(id),
 variation_merge_event_id BIGINT REFERENCES variation_merge_event(id),
 song_merge_event_id BIGINT REFERENCES song_merge_event(id)
);
