CREATE TABLE song_tag (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 name_key VARCHAR GENERATED ALWAYS AS (CST_VARIATION_NAME_KEY(name)) NOT NULL,
 CONSTRAINT song_tag_name_unique UNIQUE (name_key),
 CONSTRAINT song_tag_name_not_blank CHECK (CHAR_LENGTH(name_key)>0)
);
--;;
CREATE TABLE song_tag_assignment (
 song_id BIGINT NOT NULL REFERENCES song(id) ON DELETE CASCADE,
 tag_id BIGINT NOT NULL REFERENCES song_tag(id) ON DELETE CASCADE,
 PRIMARY KEY (song_id, tag_id)
);
