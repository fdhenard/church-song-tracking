CREATE TABLE song_merge_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 retained_song_id BIGINT NOT NULL,
 merged_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 before_data VARCHAR NOT NULL,
 after_data VARCHAR NOT NULL,
 performance_count BIGINT NOT NULL
);
--;;
CREATE TABLE song_merge_alias (
 old_song_id BIGINT PRIMARY KEY,
 canonical_song_id BIGINT NOT NULL REFERENCES song(id),
 merge_event_id BIGINT NOT NULL REFERENCES song_merge_event(id),
 original_name VARCHAR NOT NULL,
 original_artist VARCHAR NOT NULL
);

--;;
CREATE TABLE song_identity_alias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 canonical_song_id BIGINT NOT NULL REFERENCES song(id),
 merge_event_id BIGINT NOT NULL REFERENCES song_merge_event(id),
 original_name VARCHAR NOT NULL,
 original_artist VARCHAR NOT NULL
);
