CREATE TABLE service_merge_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 retained_service_id BIGINT NOT NULL,
 merged_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 before_data VARCHAR NOT NULL,
 after_data VARCHAR NOT NULL
);
--;;
CREATE TABLE service_merge_alias (
 old_service_id BIGINT PRIMARY KEY,
 canonical_service_id BIGINT NOT NULL REFERENCES church_service(id),
 merge_event_id BIGINT NOT NULL REFERENCES service_merge_event(id)
);
--;;
CREATE TABLE service_merge_source (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 church_service_id BIGINT NOT NULL REFERENCES church_service(id),
 merge_event_id BIGINT NOT NULL REFERENCES service_merge_event(id),
 original_service_id BIGINT NOT NULL,
 original_date DATE NOT NULL,
 original_title VARCHAR NOT NULL,
 vimeo_url VARCHAR,
 vimeo_video_title VARCHAR,
 youtube_url VARCHAR,
 sermon_title_image_path VARCHAR
);
